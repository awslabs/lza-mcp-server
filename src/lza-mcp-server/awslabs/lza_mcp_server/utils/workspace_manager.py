"""Workspace manager for session-isolated virtual filesystems."""

import hashlib
import logging
import os
import posixpath
import re
from typing import Any, Optional

from awslabs.lza_mcp_server.utils.auth_adapter import AuthAdapter
from awslabs.lza_mcp_server.utils.storage_adapter import StorageAdapter

logger = logging.getLogger(__name__)

SHARED_SCOPE = "shared"


class WorkspaceValidationError(Exception):
    """Raised for input validation failures (bad path, empty ID, etc.)."""


class WorkspaceNotFoundError(Exception):
    """Raised when a workspace, file, or folder does not exist."""


class WorkspaceStorageError(Exception):
    """Raised when the underlying storage adapter fails."""


class WorkspaceManager:
    """Central orchestrator for workspace operations.

    Accepts a ``StorageAdapter`` for I/O and an optional ``AuthAdapter``
    for user-scoped access.  Every path-bearing method validates the path
    before delegating to the adapter.
    """

    def __init__(
        self,
        storage: StorageAdapter,
        auth: Optional[AuthAdapter] = None,
    ) -> None:
        self._storage = storage
        self._auth = auth

    # ------------------------------------------------------------------
    # Scope resolution
    # ------------------------------------------------------------------

    def _get_scope(self, context: Any = None) -> str:
        """Return the scope directory for the current user.

        When an ``AuthAdapter`` is present and returns a user ID the scope
        is the SHA-256 hex digest of that ID.  Otherwise the scope is
        ``shared``.
        """
        if self._auth is not None:
            user_id = self._auth.get_user_id(context)
            if user_id is not None:
                return hashlib.sha256(user_id.encode()).hexdigest()
        return SHARED_SCOPE

    # Workspace IDs are generated by create_workspace() as 12-char hex strings.
    # Reject anything that doesn't match to prevent path-traversal via crafted IDs.
    _WORKSPACE_ID_RE = re.compile(r"^[0-9a-f]{12}$")

    def _resolve_workspace_path(self, workspace_id: str, context: Any = None) -> str:
        """Build the scope-aware storage path for *workspace_id*.

        Raises ``WorkspaceValidationError`` if the ID contains characters
        outside the expected hex alphabet (prevents path traversal via
        crafted workspace IDs like ``../../etc``).
        """
        if not self._WORKSPACE_ID_RE.match(workspace_id):
            raise WorkspaceValidationError("Invalid workspace ID format")
        scope = self._get_scope(context)
        return f"{scope}/{workspace_id}"

    # ------------------------------------------------------------------
    # Path validation
    # ------------------------------------------------------------------

    def validate_path(self, workspace_id: str, path: str, context: Any = None) -> str:
        """Validate and resolve *path* relative to the workspace root.

        Returns the full storage-relative path on success.

        Raises ``WorkspaceValidationError`` for:
        - empty paths
        - absolute paths
        - ``..`` traversal that escapes the workspace root
        """
        if not path:
            raise WorkspaceValidationError("File path cannot be empty")

        if os.path.isabs(path):
            logger.warning("Absolute path rejected: %s", path)
            raise WorkspaceValidationError(f"Absolute paths are not allowed: {path}")

        # Normalise using posixpath so behaviour is consistent across OS
        normalised = posixpath.normpath(path)

        # Reject any path that starts with ".." after normalisation
        if normalised == ".." or normalised.startswith("../"):
            logger.warning("Path traversal detected: %s", path)
            raise WorkspaceValidationError(f"Path traversal detected: {path}")

        workspace_root = self._resolve_workspace_path(workspace_id, context)
        full_path = f"{workspace_root}/{normalised}"

        # Double-check the resolved path is still under the workspace root
        if not full_path.startswith(workspace_root + "/"):
            logger.warning("Path traversal detected: %s", path)
            raise WorkspaceValidationError(f"Path traversal detected: {path}")

        return full_path

    def _ensure_workspace_exists(self, workspace_id: str, context: Any = None) -> None:
        """Raise ``WorkspaceNotFoundError`` if the workspace folder is absent."""
        ws_path = self._resolve_workspace_path(workspace_id, context)
        if not self._storage.exists(ws_path):
            raise WorkspaceNotFoundError("Workspace not found")

    # ------------------------------------------------------------------
    # Workspace lifecycle
    # ------------------------------------------------------------------

    def create_workspace(self, context: Any = None) -> str:
        """Create a new workspace and return its hex ID."""
        workspace_id = os.urandom(6).hex()
        ws_path = self._resolve_workspace_path(workspace_id, context)
        try:
            self._storage.create_directory(ws_path)
        except Exception as exc:
            logger.error("Failed to create workspace %s: %s", workspace_id, exc)
            raise WorkspaceStorageError(f"Failed to create workspace: {exc}") from exc
        logger.info("Workspace created: %s", workspace_id)
        return workspace_id

    def delete_workspace(self, workspace_id: str, context: Any = None) -> None:
        """Delete a workspace and all its contents."""
        self._ensure_workspace_exists(workspace_id, context)
        ws_path = self._resolve_workspace_path(workspace_id, context)
        try:
            self._storage.delete_directory(ws_path)
        except Exception as exc:
            logger.error("Failed to delete workspace %s: %s", workspace_id, exc)
            raise WorkspaceStorageError(f"Failed to delete workspace: {exc}") from exc
        logger.info("Workspace deleted: %s", workspace_id)

    def list_workspaces(self, context: Any = None) -> list[str]:
        """Return a list of workspace IDs visible to the current user."""
        scope = self._get_scope(context)
        try:
            entries = self._storage.list(scope)
        except Exception as exc:
            logger.error("Failed to list workspaces: %s", exc)
            raise WorkspaceStorageError(f"Failed to list workspaces: {exc}") from exc

        # Entries are relative to the adapter root, e.g. "shared/abc123/file.txt"
        # or "shared/abc123/" for empty workspaces.
        # Extract unique workspace IDs (the segment right after the scope).
        ids: set[str] = set()
        prefix = scope + "/"
        for entry in entries:
            if entry.startswith(prefix):
                remainder = entry[len(prefix) :]
                ws_id = remainder.split("/")[0]
                if ws_id:
                    ids.add(ws_id)
        return sorted(ids)

    # ------------------------------------------------------------------
    # File operations
    # ------------------------------------------------------------------

    def write_file(
        self,
        workspace_id: str,
        path: str,
        content: bytes,
        context: Any = None,
    ) -> None:
        """Write *content* to *path* inside the workspace.

        Auto-creates intermediate directories.
        """
        self._ensure_workspace_exists(workspace_id, context)
        full_path = self.validate_path(workspace_id, path, context)
        # Auto-create parent directories
        parent = posixpath.dirname(full_path)
        try:
            if parent and not self._storage.exists(parent):
                self._storage.create_directory(parent)
            self._storage.write(full_path, content)
        except (WorkspaceValidationError, WorkspaceNotFoundError):
            raise
        except Exception as exc:
            logger.error(
                "Failed to write file '%s' in workspace %s: %s",
                path,
                workspace_id,
                exc,
            )
            raise WorkspaceStorageError(
                f"Failed to write file '{path}': {exc}"
            ) from exc

    def read_file(
        self,
        workspace_id: str,
        path: str,
        context: Any = None,
    ) -> bytes:
        """Read and return the contents of *path* from the workspace."""
        self._ensure_workspace_exists(workspace_id, context)
        full_path = self.validate_path(workspace_id, path, context)
        try:
            return self._storage.read(full_path)
        except FileNotFoundError:
            raise WorkspaceNotFoundError(f"File '{path}' not found in workspace")
        except (WorkspaceValidationError, WorkspaceNotFoundError):
            raise
        except Exception as exc:
            logger.error(
                "Failed to read file '%s' in workspace %s: %s",
                path,
                workspace_id,
                exc,
            )
            raise WorkspaceStorageError(f"Failed to read file '{path}': {exc}") from exc

    def delete_file(
        self,
        workspace_id: str,
        path: str,
        context: Any = None,
    ) -> None:
        """Delete a file from the workspace."""
        self._ensure_workspace_exists(workspace_id, context)
        full_path = self.validate_path(workspace_id, path, context)
        try:
            if not self._storage.exists(full_path):
                raise WorkspaceNotFoundError(f"File '{path}' not found in workspace")
            self._storage.delete(full_path)
        except (WorkspaceValidationError, WorkspaceNotFoundError):
            raise
        except Exception as exc:
            logger.error(
                "Failed to delete file '%s' in workspace %s: %s",
                path,
                workspace_id,
                exc,
            )
            raise WorkspaceStorageError(
                f"Failed to delete file '{path}': {exc}"
            ) from exc

    def list_files(
        self,
        workspace_id: str,
        context: Any = None,
    ) -> list[str]:
        """Return relative file paths within the workspace."""
        self._ensure_workspace_exists(workspace_id, context)
        ws_path = self._resolve_workspace_path(workspace_id, context)
        try:
            entries = self._storage.list(ws_path)
        except Exception as exc:
            logger.error(
                "Failed to list files in workspace %s: %s",
                workspace_id,
                exc,
            )
            raise WorkspaceStorageError(
                f"Failed to list files in workspace: {exc}"
            ) from exc

        prefix = ws_path + "/"
        return sorted(
            entry[len(prefix) :] for entry in entries if entry.startswith(prefix)
        )

    # ------------------------------------------------------------------
    # Folder operations
    # ------------------------------------------------------------------

    def create_folder(
        self,
        workspace_id: str,
        path: str,
        context: Any = None,
    ) -> None:
        """Create a folder (and intermediates) inside the workspace."""
        self._ensure_workspace_exists(workspace_id, context)
        full_path = self.validate_path(workspace_id, path, context)
        try:
            self._storage.create_directory(full_path)
        except (WorkspaceValidationError, WorkspaceNotFoundError):
            raise
        except Exception as exc:
            logger.error(
                "Failed to create folder '%s' in workspace %s: %s",
                path,
                workspace_id,
                exc,
            )
            raise WorkspaceStorageError(
                f"Failed to create folder '{path}': {exc}"
            ) from exc

    def delete_folder(
        self,
        workspace_id: str,
        path: str,
        context: Any = None,
    ) -> None:
        """Delete a folder and all its contents from the workspace."""
        self._ensure_workspace_exists(workspace_id, context)
        full_path = self.validate_path(workspace_id, path, context)
        try:
            if not self._storage.exists(full_path):
                raise WorkspaceNotFoundError(f"Folder '{path}' not found in workspace")
            self._storage.delete_directory(full_path)
        except (WorkspaceValidationError, WorkspaceNotFoundError):
            raise
        except Exception as exc:
            logger.error(
                "Failed to delete folder '%s' in workspace %s: %s",
                path,
                workspace_id,
                exc,
            )
            raise WorkspaceStorageError(
                f"Failed to delete folder '{path}': {exc}"
            ) from exc
